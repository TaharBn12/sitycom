const STORAGE_KEY = 'sitycom.lang';
let current = localStorage.getItem(STORAGE_KEY) || 'ar';
if (!dict[current]) current = 'ar';

const listeners = new Set();

export function getLang() {
  return current;
}

export function setLang(lang) {
  if (!dict[lang]) return;
  current = lang;
  localStorage.setItem(STORAGE_KEY, lang);
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  applyTranslations();
  listeners.forEach((fn) => fn(lang));
}

export function onLangChange(fn) {
  listeners.add(fn);
}

export function t(key, params = {}) {
  const table = dict[current] || dict.ar;
  let value = table[key];
  if (value === undefined) value = (dict.ar[key] !== undefined ? dict.ar[key] : key);
  return Object.entries(params).reduce((acc, [k, v]) => acc.replaceAll(`{${k}}`, v), value);
}

/** يطبق الترجمة على العناصر التي تحمل data-i18n */
export function applyTranslations(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
    el.setAttribute('aria-label', t(el.dataset.i18nTitle));
  });
}

export function initI18n() {
  document.documentElement.lang = current;
  document.documentElement.dir = current === 'ar' ? 'rtl' : 'ltr';
  applyTranslations();
}

