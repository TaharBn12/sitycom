-- ── لوحة المعلومات ──────────────────────────────────────────────────
create or replace function public.dashboard_data(p_days integer default 30)
returns jsonb
language plpgsql stable
as $$
declare
  v_since text;
begin
  v_since := to_char(now() - make_interval(days => p_days), 'YYYY-MM-DD HH24:MI:SS');
  return jsonb_build_object(
    'cards', jsonb_build_object(
      'orders',        (select count(*) from public.orders where created_at >= v_since),
      'revenue',       coalesce((select sum(total) from public.orders where created_at >= v_since), 0),
      'shipping',      coalesce((select sum(shipping_fee) from public.orders where created_at >= v_since), 0),
      'discount',      coalesce((select sum(discount) from public.orders where created_at >= v_since), 0),
      'pending',       (select count(*) from public.orders where status in ('draft','prete_a_expedier','en_preparation','en_preparation_stock')),
      'in_transit',    (select count(*) from public.orders where status in ('en_ramassage','vers_hub','en_hub','vers_wilaya','en_livraison')),
      'delivered',     (select count(*) from public.orders where status in ('livre_non_encaisse','encaisse_non_paye','paiements_prets','paye_et_archive')),
      'returns',       (select count(*) from public.orders where status like 'retour%'),
      'suspended',     (select count(*) from public.orders where status = 'suspendu'),
      'not_pushed',    (select count(*) from public.orders o left join public.shipments s on s.order_id = o.id
                          where s.tracking is null or s.tracking = ''),
      'collected',     coalesce((select sum(total) from public.orders where status in ('encaisse_non_paye','paiements_prets','paye_et_archive')), 0),
      'customers',     (select count(*) from public.customers),
      'new_customers', (select count(*) from public.customers where created_at >= v_since)
    ),
    'statusCounts', coalesce((
      select jsonb_agg(jsonb_build_object('status', t.st, 'count', t.c) order by t.c desc)
      from (select coalesce(s.ecotrack_status, o.status) as st, count(*) as c
            from public.orders o left join public.shipments s on s.order_id = o.id
            group by 1) t
    ), '[]'::jsonb),
    'daily', coalesce((
      select jsonb_agg(jsonb_build_object('day', t.day, 'orders', t.orders, 'revenue', t.revenue) order by t.day)
      from (select left(created_at, 10) as day, count(*) as orders, coalesce(sum(total), 0) as revenue
            from public.orders where created_at >= v_since group by 1) t
    ), '[]'::jsonb),
    'topWilayas', coalesce((
      select jsonb_agg(jsonb_build_object('wilaya_id', t.wilaya_id, 'wilaya_name', t.wilaya_name,
                                          'orders', t.orders, 'revenue', t.revenue) order by t.orders desc)
      from (select o.wilaya_id, o.wilaya_name, count(*) as orders, coalesce(sum(o.total), 0) as revenue
            from public.orders o where o.created_at >= v_since
            group by o.wilaya_id, o.wilaya_name order by orders desc limit 8) t
    ), '[]'::jsonb),
    'topProducts', coalesce((
      select jsonb_agg(jsonb_build_object('name', t.name, 'qty', t.qty, 'revenue', t.revenue) order by t.qty desc)
      from (select oi.name, sum(oi.qty) as qty, coalesce(sum(oi.line_total), 0) as revenue
            from public.order_items oi join public.orders o on o.id = oi.order_id
            where o.created_at >= v_since group by oi.name order by qty desc limit 8) t
    ), '[]'::jsonb),
    'recent', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', t.id, 'order_number', t.order_number, 'customer_name', t.customer_name,
        'phone', t.phone, 'wilaya_name', t.wilaya_name, 'total', t.total, 'status', t.status,
        'created_at', t.created_at, 'tracking', t.tracking, 'ecotrack_status', t.ecotrack_status
      ) order by t.id desc)
      from (select o.id, o.order_number, o.customer_name, o.phone, o.wilaya_name, o.total, o.status,
                   o.created_at, s.tracking, s.ecotrack_status
            from public.orders o left join public.shipments s on s.order_id = o.id
            order by o.id desc limit 10) t
    ), '[]'::jsonb),
    'lowStock', coalesce((
      select jsonb_agg(jsonb_build_object('id', id, 'name_ar', name_ar, 'sku', sku, 'stock', stock) order by stock asc)
      from (select id, name_ar, sku, stock from public.products
            where active = 1 and stock <= 5 order by stock asc limit 8) t
    ), '[]'::jsonb)
  );
end $$;

-- ── التقارير المفصّلة ───────────────────────────────────────────────
create or replace function public.reports_data(p_from text, p_to text)
returns jsonb
language plpgsql stable
as $$
begin
  return jsonb_build_object(
    'summary', coalesce((
      select jsonb_build_object('orders', count(*), 'revenue', coalesce(sum(total), 0),
        'shipping', coalesce(sum(shipping_fee), 0), 'discount', coalesce(sum(discount), 0),
        'avg_order', coalesce(avg(total), 0))
      from public.orders where left(created_at, 10) between p_from and p_to
    ), '{}'::jsonb),
    'byDay', coalesce((
      select jsonb_agg(jsonb_build_object('day', t.day, 'orders', t.orders, 'revenue', t.revenue,
                                          'shipping', t.shipping) order by t.day)
      from (select left(created_at, 10) as day, count(*) as orders, coalesce(sum(total), 0) as revenue,
              coalesce(sum(shipping_fee), 0) as shipping
            from public.orders where left(created_at, 10) between p_from and p_to group by 1) t
    ), '[]'::jsonb),
    'byWilaya', coalesce((
      select jsonb_agg(jsonb_build_object('wilaya_id', t.wilaya_id, 'wilaya_name', t.wilaya_name,
        'orders', t.orders, 'revenue', t.revenue, 'shipping', t.shipping,
        'returns', t.returns, 'delivered', t.delivered) order by t.orders desc)
      from (select o.wilaya_id, o.wilaya_name, count(*) as orders,
              coalesce(sum(o.total), 0) as revenue, coalesce(sum(o.shipping_fee), 0) as shipping,
              sum(case when o.status like 'retour%' then 1 else 0 end) as returns,
              sum(case when o.status in ('livre_non_encaisse','encaisse_non_paye','paiements_prets','paye_et_archive') then 1 else 0 end) as delivered
            from public.orders o where left(o.created_at, 10) between p_from and p_to
            group by o.wilaya_id, o.wilaya_name) t
    ), '[]'::jsonb),
    'byProduct', coalesce((
      select jsonb_agg(jsonb_build_object('name', t.name, 'sku', t.sku, 'qty', t.qty,
                                          'revenue', t.revenue) order by t.revenue desc)
      from (select oi.name, oi.sku, sum(oi.qty) as qty, coalesce(sum(oi.line_total), 0) as revenue
            from public.order_items oi join public.orders o on o.id = oi.order_id
            where left(o.created_at, 10) between p_from and p_to
            group by oi.name, oi.sku order by revenue desc limit 50) t
    ), '[]'::jsonb),
    'byStatus', coalesce((
      select jsonb_agg(jsonb_build_object('status', t.status, 'count', t.count,
                                          'revenue', t.revenue) order by t.count desc)
      from (select coalesce(s.ecotrack_status, o.status) as status, count(*) as count,
              coalesce(sum(o.total), 0) as revenue
            from public.orders o left join public.shipments s on s.order_id = o.id
            where left(o.created_at, 10) between p_from and p_to group by 1) t
    ), '[]'::jsonb),
    'byDeliveryType', coalesce((
      select jsonb_agg(jsonb_build_object('kind', t.kind, 'count', t.count, 'shipping', t.shipping))
      from (select case when o.stop_desk = 1 then 'stopdesk' else 'home' end as kind,
              count(*) as count, coalesce(sum(o.shipping_fee), 0) as shipping
            from public.orders o where left(o.created_at, 10) between p_from and p_to
            group by 1) t
    ), '[]'::jsonb),
    'deliveryPerformance', coalesce((
      select jsonb_agg(jsonb_build_object('status', t.status, 'count', t.count,
                                          'delivery_fees', t.delivery_fees) order by t.count desc)
      from (select s.ecotrack_status as status, count(*) as count,
              coalesce(sum(s.delivery_fee), 0) as delivery_fees
            from public.shipments s join public.orders o on o.id = s.order_id
            where left(o.created_at, 10) between p_from and p_to
              and s.tracking is not null and s.tracking <> ''
            group by s.ecotrack_status) t
    ), '[]'::jsonb)
  );
end $$;

-- ── قائمة الطلبيات مع الفلاتر (صفحة واحدة + العدد + التوزيع) ───────
create or replace function public.orders_page(
  p_q text default null,
  p_statuses text[] default null,
  p_wilaya integer default null,
  p_pushed integer default null,          -- null = الكل · 1 = مرسلة · 0 = غير مرسلة
  p_start text default null,
  p_end text default null,
  p_payment text default null,
  p_delivery integer default null,        -- null = الكل · 1 = مكتب · 0 = منزل
  p_limit integer default 25,
  p_offset integer default 0
)
returns jsonb
language plpgsql stable
as $$
declare
  v_q text;
begin
  v_q := lower(coalesce(p_q, ''));
  return jsonb_build_object(
    'orders', coalesce((
      with base as (
        select o.*, s.tracking, s.ecotrack_status, s.type as ship_type, s.pushed_at,
               s.validated_at, s.return_asked_at, s.last_activity, s.last_activity_at,
               (select count(*) from public.order_items oi where oi.order_id = o.id) as items_count
        from public.orders o
        left join public.shipments s on s.order_id = o.id
        where
          (p_q is null
            or lower(o.order_number) like '%' || v_q || '%'
            or lower(o.customer_name) like '%' || v_q || '%'
            or o.phone like '%' || p_q || '%'
            or s.tracking like '%' || p_q || '%'
            or s.reference like '%' || p_q || '%')
          and (p_statuses is null or o.status = any (p_statuses) or s.ecotrack_status = any (p_statuses))
          and (p_wilaya is null or o.wilaya_id = p_wilaya)
          and (p_pushed is null
            or (p_pushed = 1 and s.tracking is not null and s.tracking <> '')
            or (p_pushed = 0 and (s.tracking is null or s.tracking = '')))
          and (p_start is null or left(o.created_at, 10) >= p_start)
          and (p_end is null or left(o.created_at, 10) <= p_end)
          and (p_payment is null or o.payment_status = p_payment)
          and (p_delivery is null or o.stop_desk = p_delivery)
      )
      select jsonb_agg(row_to_json(t) order by t.id desc)
      from (select * from base order by id desc limit greatest(p_limit, 1) offset greatest(p_offset, 0)) t
    ), '[]'::jsonb),
    'total', (
      select count(*)
      from public.orders o left join public.shipments s on s.order_id = o.id
      where
        (p_q is null
          or lower(o.order_number) like '%' || v_q || '%'
          or lower(o.customer_name) like '%' || v_q || '%'
          or o.phone like '%' || p_q || '%'
          or s.tracking like '%' || p_q || '%'
          or s.reference like '%' || p_q || '%')
        and (p_statuses is null or o.status = any (p_statuses) or s.ecotrack_status = any (p_statuses))
        and (p_wilaya is null or o.wilaya_id = p_wilaya)
        and (p_pushed is null
          or (p_pushed = 1 and s.tracking is not null and s.tracking <> '')
          or (p_pushed = 0 and (s.tracking is null or s.tracking = '')))
        and (p_start is null or left(o.created_at, 10) >= p_start)
        and (p_end is null or left(o.created_at, 10) <= p_end)
        and (p_payment is null or o.payment_status = p_payment)
        and (p_delivery is null or o.stop_desk = p_delivery)
    ),
    'stats', coalesce((
      select jsonb_agg(jsonb_build_object('st', t.st, 'c', t.c) order by t.c desc)
      from (select coalesce(s.ecotrack_status, o.status) as st, count(*) as c
            from public.orders o left join public.shipments s on s.order_id = o.id
            group by 1) t
    ), '[]'::jsonb)
  );
end $$;

-- ── إحصائيات العملاء (عدد الطلبيات وإجمالي المشتريات لكل هاتف) ─────
create or replace function public.customers_stats(p_phones text[])
returns table (phone text, orders_count bigint, total_spent double precision)
language sql stable
as $$
  select o.phone,
         count(*) as orders_count,
         coalesce(sum(o.total), 0)::float8 as total_spent
  from public.orders o
  where o.phone = any (p_phones)
  group by o.phone;
$$;

-- ── تعديل المخزون زيادة/نقصاناً بدون ما تحت الصفر ─────────────────
create or replace function public.product_adjust_stock(p_id bigint, p_delta integer)
returns void
language sql
as $$
  update public.products
  set stock = greatest(0, stock + p_delta),
      updated_at = public.app_now()
  where id = p_id;
$$;

