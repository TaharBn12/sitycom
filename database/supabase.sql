-- ── سياسة أمان واحدة لكل الجداول (تطبيق داخلي بمفتاح الخادم) ──────

do $$
declare t text;
begin
  foreach t in array array[
    'users','sessions','settings','categories','products','customers','orders',
    'order_items','shipments','order_events','wilayas','communes','desks',
    'shipping_fees','ecotrack_products','activity_log','sync_jobs'
  ]
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists %I on public.%I', t || '_app_access', t);
    execute format(
      'create policy %I on public.%I for all to anon, authenticated using (true) with check (true)',
      t || '_app_access', t);
  end loop;
end $$;

